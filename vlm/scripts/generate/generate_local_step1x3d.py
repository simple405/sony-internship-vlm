#!/usr/bin/env python3
"""
Step1X-3D Offline 3D Mesh and Texture Generation Pipeline
==========================================================

This script drives a fully **offline**, server-local execution of the
Step1X-3D two-stage 3D generation pipeline for anime IP merchandise
supervision.  It takes a cleaned, white-background reference image of
a character (plus a foreground silhouette mask) and produces:

Stage 1 - Geometry
    A watertight 3D mesh in GLB format extracted from a neural occupancy
    field, generated by the Step1X-3D-Geometry-1300m diffusion model.

Stage 2 - Texture
    A fully textured version of the geometry GLB, produced by the
    Step1X-3D-Texture pipeline (SDXL-based image-guided multi-view
    diffusion with IP-Adapter-XL / IG2MV).

Both stages write a JSON manifest recording input hashes, model
revisions, and all generation settings so that results are fully
reproducible and traceable back to a specific source image.

Inputs required
---------------
- A cleaned white-background PNG of the character front view
  (typically ``cleaned_white.png`` from the local pipeline).
- A binary/greyscale foreground mask PNG that isolates the character
  from the background (typically ``foreground_mask.png``).
- All model weights present at the server-local paths defined by the
  module-level constants (Step1X-3D-Geometry, Step1X-3D-Texture,
  SDXL-base-1.0, sdxl-vae-fp16-fix).

Outputs produced
----------------
``<output_dir>/char_001_geometry.glb``
    Raw geometry mesh from Stage 1.
``<output_dir>/char_001_textured.glb``
    Textured mesh from Stage 2.
``<output_dir>/char_001_transparent_input.png``
    The RGBA composite used as the geometry stage input (source + mask).
``<output_dir>/texture_intermediates/``
    Per-iteration view renders saved by the texture pipeline.
``<output_dir>/manifest.json``
    Full provenance record: timestamps, SHA-256 digests, model paths,
    and all generation settings.

Conda environment
-----------------
Run this script inside the ``step1x3d`` conda environment on the
inference server::

    conda activate step1x3d
    python generate_local_step1x3d.py [--stage geometry|texture|all]

The environment must have PyTorch >= 2.2, diffusers, transformers,
trimesh, Pillow, and the Step1X-3D source tree on ``sys.path``
(handled automatically via the ``STEP1X_CODE`` constant below).

Network policy
--------------
All Hugging Face hub calls are forced offline via environment variables
set at import time, ensuring no accidental model downloads on the
air-gapped inference server.
"""

